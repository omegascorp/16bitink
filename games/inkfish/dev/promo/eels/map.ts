const toPx = (coast: Coast): Pt[] => coast.map(([lon, lat]) => project(lon, lat));

/** The faint lines of latitude and longitude, every 10°, dotted. */
function drawGraticule(ctx: CanvasRenderingContext2D): void {
  ctx.save();
  ctx.strokeStyle = SEA_INK;
  ctx.globalAlpha = 0.22;
  ctx.lineWidth = 1.6;
  ctx.setLineDash([3, 9]);
  for (let lon = -80; lon <= 20; lon += 10) {
    const x = project(lon, 0).x;
    ctx.beginPath();
    ctx.moveTo(x, MAP_TOP);
    ctx.lineTo(x, MAP_BOTTOM);
    ctx.stroke();
  }
  for (let lat = 10; lat <= 70; lat += 10) {
    const y = project(0, lat).y;
    ctx.beginPath();
    ctx.moveTo(0, y);
    ctx.lineTo(VIDEO.width, y);
    ctx.stroke();
  }
  ctx.restore();
}

/** The map, in screen px (before render.ts zooms it). */
export function makeMap(): Prop {
  return prop(VIDEO.width, 1140, 2022, (pen, ctx) => {
    ctx.save();
    washPath(ctx, MAP_TOP, MAP_BOTTOM, VIDEO.width, 61);
    ctx.fillStyle = SEA;
    ctx.globalAlpha = 0.55;
    ctx.fill();
    ctx.globalAlpha = 1;
    ctx.clip();
    drawGraticule(ctx);
    for (const coast of [EUROPE, AFRICA, BRITAIN, IRELAND, ICELAND, GREENLAND, NORTH_AMERICA, CENTRAL_AMERICA, ...ISLANDS]) inked(pen, toPx(coast), LAND, 2.4);
    for (const p of toPx(DOTS)) pen.dot(p.x, p.y, 4.2, INK, 0.9);
    // Ripples off the coasts, as old charts have them.
    for (const p of toPx([[-12, 44], [-12, 38], [-20, 24], [-20, 16], [-68, 38], [-76, 30], [-63, 42]])) {
      for (let k = 0; k < 2; k++) pen.hair([{ x: p.x - 18, y: p.y + k * 9 }, { x: p.x - 6, y: p.y - 4 + k * 9 }, { x: p.x + 6, y: p.y + k * 9 }, { x: p.x + 18, y: p.y - 4 + k * 9 }], 1.4, SEA_INK, 0.45);
    }
    ctx.restore();
    const at = (lon: number, lat: number): Pt => project(lon, lat);
    drawTextLine(ctx, 'AFRICA', at(-4, 20).x, at(-4, 20).y, 48, 700, 0.8, NAME);
    drawTextLine(ctx, 'N. AMERICA', at(-80, 40).x + 30, at(-80, 40).y, 40, 700, 0.8, NAME);
    drawTextLine(ctx, 'Atlantic Ocean', at(-33, 52).x, at(-33, 52).y, 54, 500, 0.75, OCEAN);
  });
}
