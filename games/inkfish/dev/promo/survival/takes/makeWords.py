"""Writes words.ts from takes/words.json (Scribe on voice.mp3) and takes/durations.txt (assemble.sh)."""
import json, sys
GAP = 1.5
durs = [(l.split()[0], float(l.split()[1])) for l in open('takes/durations.txt')]
sections, t = [], 0.0
for i, (_, d) in enumerate(durs):
    sections.append((t, t + d)); t += d + GAP
total = sections[-1][1]
raw = [w for w in json.load(open('takes/words.json'))['words'] if w.get('type') == 'word']
FIX = {'mollusk.': 'mollusc.', 'lineup': 'line-up', 'Inkfish.': 'InkFish.', 'sixteenbit.ink.': '16bit.ink.',
       'minutis,': 'minutus,', 'minutis.': 'minutus.', 'kilometers': 'kilometres', 'canceled.': 'cancelled.',
       'seawater.': 'sea water.'}
words = []
for w in raw:
    text = FIX.get(w['text'], w['text'])
    if words and words[-1][0].lower() == 'ice' and text.lower().startswith('fish'):
        p = words.pop(); words.append(('icefish' + text[4:], p[1], w['end'])); continue
    words.append((text, w['start'], w['end']))
def section(t):
    return next(i for i, (a, b) in enumerate(sections) if t <= b + GAP / 2)
out = ['/**',
 ' * The narration (voice.mp3): ElevenLabs, voice "Mark – Natural Conversations"',
 f' * (eleven_v4), one take per block of script.md ({", ".join(p for p, _ in durs)}),',
 ' * edge silence trimmed at -45 dB, sped up 1.05x (pitch kept) and laid on one track',
 f' * with {GAP} s between blocks (assemble.sh). WORDS are its words with start and end',
 ' * times in seconds on that track (ElevenLabs Scribe), spelt as in the script;',
 ' * SECTIONS are when each block\'s take starts and ends.',
 ' * Generated by takes/makeWords.py: edit script.md and regenerate, don\'t hand-edit the timings.',
 ' */', '',
 'export interface Word {', '  readonly text: string;', '  readonly start: number;', '  readonly end: number;',
 '  /** Which block of the script it\'s in (SECTIONS, 0-based: block 1 is 0). */', '  readonly section: number;', '}', '',
 'export interface Section {', '  readonly start: number;', '  readonly end: number;', '}', '',
 '/** The track\'s length. */', f'export const VOICE_S = {total:.3f};', '',
 'export const SECTIONS: readonly Section[] = [']
out += [f'  {{ start: {a:.3f}, end: {b:.3f} }},' for a, b in sections]
out += ['];', '', 'const w = (text: string, start: number, end: number, section: number): Word => ({ text, start, end, section });', '',
        'export const WORDS: readonly Word[] = [']
out += [f'  w({json.dumps(t)}, {a:g}, {b:g}, {section(a)}),' for t, a, b in words]
out += ['];', '']
open('words.ts', 'w').write('\n'.join(out))
print(len(words), 'words', 'total', round(total, 2))
for i in range(len(sections)):
    ws = [x for x in words if section(x[1]) == i]
    print(i, sections[i], ws[0][0], '…', ws[-1][0], round(ws[0][1], 2), round(ws[-1][2], 2))
