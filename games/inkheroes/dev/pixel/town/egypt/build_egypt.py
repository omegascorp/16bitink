"""Builds Egypt's town art into src/art/pixel/town-kemet/ and lists it in src/art/pixel/townKemet.ts.

  python3 dev/pixel/town/egypt/build_egypt.py

Sources: iso/*.png, PixelLab create_image_pixen (the Greek city's prompt pattern: "<building>, seen in
three-quarter view from above, the front and the left side both visible, standing on a small square of
pale sandstone paving stones, isolated shape with a flat bottom edge and nothing behind it"), jobs.txt
lists the job of each (fetchall.sh downloads them). The walls' pieces are edit_image_pixen repaints of
the Greek wall pieces (same canvas, so townWalls.ts's foot lines hold), see walls.py. Every sprite is
trimmed to its pixels and its grey drop shadow peeled off; its feet are the middle of its bottom row.
The keys are the Greek city's (a Levy Camp is the 'guardhouse'), so the layout code is shared.
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / 'map'))
from build_map import trimmed  # noqa: E402
from PIL import Image  # noqa: E402

GAME = HERE.parents[3]
OUT = GAME / 'src' / 'art' / 'pixel' / 'town-kemet'
TS = GAME / 'src' / 'art' / 'pixel' / 'townKemet.ts'

DWELLINGS = ['guardhouse', 'archeryRange', 'griffinTower', 'barracks', 'monastery', 'tiltyard', 'seraphSpire']
PIECES = [
    'hall-village', 'hall-town', 'hall-city', 'hall-capitol', 'walls-fort', 'walls-citadel', 'walls-castle',
    'guild-1', 'guild-2', 'templeOsiris', 'tavern', 'blacksmith', 'marketplace', 'stables', 'storehouse', 'treasury',
    'portal', 'portal-2', 'portal-3',
    *DWELLINGS, *[f'{d}-{n}' for d in DWELLINGS for n in (2, 3)],
    *[f'house-{k}' for k in 'abcdef'], 'fountain', 'palm-a', 'palm-b',
    'wall', 'wall-up', 'wall-gate', 'corner-front', 'corner-back', 'corner-left', 'corner-left-rear', 'corner-right', 'corner-right-rear',
]


KEPT = ['wall', 'wall-up', 'wall-gate', 'corner-front', 'corner-back', 'corner-left', 'corner-left-rear', 'corner-right', 'corner-right-rear']


def peel_shadow(im: Image.Image) -> Image.Image:
    """Removes the neutral-grey drop shadow the generator leaves under a building: grey pixels reachable from the outside."""
    px = im.load()
    w, h = im.size

    def grey(x: int, y: int) -> bool:
        r, g, b, a = px[x, y]
        return a > 0 and abs(r - g) < 7 and abs(g - b) < 7 and 70 <= r <= 165

    seen, stack = set(), []
    for y in range(h):
        for x in range(w):
            if px[x, y][3] == 0:
                stack.append((x, y))
    while stack:
        x, y = stack.pop()
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1), (x + 1, y + 1), (x - 1, y - 1), (x + 1, y - 1), (x - 1, y + 1)):
            if 0 <= nx < w and 0 <= ny < h and (nx, ny) not in seen and px[nx, ny][3] != 0 and grey(nx, ny):
                seen.add((nx, ny))
                px[nx, ny] = (0, 0, 0, 0)
                stack.append((nx, ny))
    return im


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    imports, entries, names = [], [], []
    for name in PIECES:
        src = HERE / 'iso' / f'{name}.png'
        if not src.exists():
            print('MISSING', name)
            continue
        raw = Image.open(src).convert('RGBA')
        if name not in KEPT:
            raw = peel_shadow(raw)
            tmp = HERE / 'iso' / f'.{name}.clean.png'
            raw.save(tmp)
            im = trimmed(tmp)
            tmp.unlink()
        else:
            # Kept on the Greek piece's canvas (not trimmed): townWalls.ts's foot lines and corner points count from its top-left.
            im = raw.copy()
            q = im.load()
            for y in range(im.height):
                for x in range(im.width):
                    r, g, b, a = q[x, y]
                    q[x, y] = (r, g, b, 255) if a >= 128 else (0, 0, 0, 0)
        i = len(names)
        im.save(OUT / f'{name}.png')
        imports.append(f"import p{i} from './town-kemet/{name}.png?url';")
        entries.append(f"  '{name}': {{ url: p{i}, w: {im.width}, h: {im.height} }},")
        names.append(name)
        print(name, im.size)
    imports.append("import paving from './town-kemet/paving.png?url';")
    pv = HERE / 'iso' / 'paving.png'
    if pv.exists():
        Image.open(pv).convert('RGBA').save(OUT / 'paving.png')
    flags = HERE / 'flags.ts.txt'
    TS.write_text('\n'.join([
        '// Generated by dev/pixel/town/egypt/build_egypt.py: do not edit.',
        *imports,
        "import type { TownSprite } from './town';",
        '',
        f"export type KemetArt = {' | '.join(repr(n) for n in names)};",
        '',
        "/** Egypt's city: the Greek city's keys (a Levy Camp is the 'guardhouse'), plus its own Temple of Osiris and palms. */",
        'export const KEMET_ART: Readonly<Record<KemetArt, TownSprite>> = {',
        *entries,
        '};',
        '',
        "/** Egypt's paving (sandstone flags, isometric already). */",
        'export const KEMET_PAVING = paving;',
        '',
        flags.read_text() if flags.exists() else '',
    ]))


if __name__ == '__main__':
    main()
