"""Builds the town screen's pixel art into src/art/pixel/town/ and lists it in
src/art/pixel/town.ts.

  python3 dev/pixel/town/build_town.py

Sources: iso/*.png, PixelLab create_image_pixen, every one "<building>, seen in
three-quarter view from above, the front and the left side both visible,
standing on a small square of pale paving stones, nothing else around it"
(view side), so the whole town shares one isometric angle and each building
its paving. src/*.png are the earlier front elevations, kept for reference. Every
sprite is trimmed to its pixels; its feet are the middle of its bottom row.
"""
