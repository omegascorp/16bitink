# The streets' paving, already drawn at the town's isometric angle (tiled as it is).
PAVING = 'paving.png'


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    imports, entries = [], []
    for i, (name, (src, rows)) in enumerate(PIECES.items()):
        im = trimmed(HERE / 'iso' / src, rows)
        im.save(OUT / f'{name}.png')
        imports.append(f"import p{i} from './town/{name}.png?url';")
        entries.append(f"  '{name}': {{ url: p{i}, w: {im.width}, h: {im.height} }},")
        print(name, im.size)
    Image.open(HERE / 'iso' / PAVING).convert('RGBA').save(OUT / 'paving.png')
    imports.append("import paving from './town/paving.png?url';")
    names = ' | '.join(f"'{n}'" for n in PIECES)
    TS.write_text('\n'.join([
        '// Generated by dev/pixel/town/build_town.py: do not edit.',
        *imports,
        '',
        '/** One town sprite: its url and size; it stands on the middle of its bottom row. */',
        'export interface TownSprite {',
        '  readonly url: string;',
        '  readonly w: number;',
        '  readonly h: number;',
        '}',
        '',
        f'export type TownArt = {names};',
        '',
        'export const TOWN_ART: Readonly<Record<TownArt, TownSprite>> = {',
        *entries,
        '};',
        '',
        '/** The streets\' paving swatch (isometric already; tiled as it is). */',
        'export const TOWN_PAVING = paving;',
        '',
    ]))


if __name__ == '__main__':
    main()
