GAME = HERE.parents[2]
OUT = GAME / 'src' / 'art' / 'pixel' / 'town'
TS = GAME / 'src' / 'art' / 'pixel' / 'town.ts'

# piece -> (source under iso/, rows kept from the top or None for all)
