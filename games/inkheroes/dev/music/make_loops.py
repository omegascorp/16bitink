"""Turns the chosen ElevenLabs takes into the game's looping tracks: finds where a take best meets its own
start, blends the join, evens the loudness, pads both ends and writes src/audio/music/*.mp3 and src/audio/tracks.ts.
  python3 dev/music/make_loops.py                 -> the tracks, from dev/music/raw/<id>.mp3
  python3 dev/music/make_loops.py --score a.mp3 … -> how well each take would loop, best first"""
import subprocess
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
GAME = HERE.parents[1]
OUT = GAME / 'src' / 'audio' / 'music'
RATE = 44100
# Sound kept on either side of the loop, so an encoder's delay never reaches it, seconds.
PAD = 0.5
# Where a loop starts, how far before the end it may stop, and the stretch compared to find the join, seconds.
HEAD = 3.0
SEARCH = (4.0, 32.0)
WINDOW = 5.0
FRAME = 4096
HOP = 882
BANDS = 48
# Track id, its blend at the join (seconds) and its loudness (RMS, dBFS): a calm track blends slowly and sits lower.
TRACKS = (('map', 3.0, -23.0), ('townGreek', 2.0, -22.0), ('battle', 0.6, -20.0))
PEAK = 0.95


def decode(path: Path) -> np.ndarray:
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(path), '-f', 'f32le', '-ac', '2', '-ar', str(RATE), '-'], check=True, capture_output=True).stdout
    return np.frombuffer(raw, dtype=np.float32).reshape(-1, 2).copy()


def spectrum(audio: np.ndarray) -> np.ndarray:
    """The sound through time: one unit vector of log-spaced band levels per frame, so like-sounding frames score near 1."""
    mono = audio.mean(axis=1)
    starts = np.arange(0, len(mono) - FRAME, HOP)
    frames = np.stack([mono[i:i + FRAME] for i in starts]) * np.hanning(FRAME)
    power = np.abs(np.fft.rfft(frames, axis=1)) ** 2
    edges = np.unique(np.geomspace(3, FRAME // 2, BANDS + 1).astype(int))
    bands = np.stack([power[:, a:b].sum(axis=1) for a, b in zip(edges, edges[1:])], axis=1)
    level = np.log1p(bands * 1e3)
    return level / (np.linalg.norm(level, axis=1, keepdims=True) + 1e-9)


def best_join(audio: np.ndarray) -> tuple[int, float]:
    """The sample where the take comes closest to repeating its start, and how close (1 is identical)."""
    sound = spectrum(audio)
    win = int(WINDOW * RATE / HOP)
    want = sound[int(HEAD * RATE / HOP):][:win]
    first = int((len(audio) / RATE - SEARCH[1]) * RATE / HOP)
    last = int((len(audio) / RATE - SEARCH[0]) * RATE / HOP) - win
    scores = [float((want * sound[at:at + win]).sum(axis=1).mean()) for at in range(first, last)]
    at = first + int(np.argmax(scores))
    return nudge(audio, at * HOP), max(scores)


def nudge(audio: np.ndarray, at: int) -> int:
    """`at` moved a hair so the waves themselves line up with the loop's start."""
    mono = audio.mean(axis=1)
    head = int(HEAD * RATE)
    size = RATE // 2
    reach = RATE // 20
    want = mono[head:head + size]
    return at - reach + int(np.argmax([np.dot(want, mono[i:i + size]) for i in range(at - reach, at + reach)]))


def steadiness(audio: np.ndarray) -> float:
    """How far apart the quietest and loudest stretches of the middle are, dB: lower is steadier."""
    chunk = RATE * 5
    levels = [20 * np.log10(np.sqrt(np.mean(audio[i:i + chunk] ** 2)) + 1e-9) for i in range(chunk, len(audio) - chunk, chunk)]
    return float(max(levels) - min(levels))


def build(track: str, blend_s: float, loudness: float) -> tuple[float, float]:
    audio = decode(HERE / 'raw' / f'{track}.mp3')
    start = int(HEAD * RATE)
    end, score = best_join(audio)
    blend = int(blend_s * RATE)
    loop = audio[start:end].copy()
    # Equal-power: the take's end gives way to what leads into the loop's start.
    u = np.linspace(0, 1, blend, dtype=np.float32)[:, None]
    loop[-blend:] = loop[-blend:] * np.cos(u * np.pi / 2) + audio[start - blend:start] * np.sin(u * np.pi / 2)
    gain = 10 ** (loudness / 20) / np.sqrt(np.mean(loop ** 2))
    loop = loop * min(gain, PEAK / np.abs(loop).max())
    pad = int(PAD * RATE)
    full = np.concatenate([loop[-pad:], loop, loop[:pad]])
    OUT.mkdir(exist_ok=True)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'f32le', '-ac', '2', '-ar', str(RATE), '-i', '-', '-b:a', '112k', str(OUT / f'{track}.mp3')], input=full.astype(np.float32).tobytes(), check=True)
    print(f'{track}: loop {len(loop) / RATE:.1f}s, join {score:.2f}, {(OUT / f"{track}.mp3").stat().st_size // 1024} KB')
    return PAD, PAD + len(loop) / RATE


def write_tracks(points: dict[str, tuple[float, float]]) -> None:
    ids = list(points)
    lines = ['// Generated by dev/music/make_loops.py: do not edit by hand.']
    lines += [f"import {t} from './music/{t}.mp3?url';" for t in ids]
    lines += ['', f"export type TrackId = {' | '.join(repr(t) for t in ids)};", '', '/** Each track, with the seconds its loop runs between. */']
    lines += ['export const MUSIC_TRACKS: Readonly<Record<TrackId, { readonly url: string; readonly loopStart: number; readonly loopEnd: number }>> = {']
    lines += [f'  {t}: {{ url: {t}, loopStart: {a}, loopEnd: {b:.3f} }},' for t, (a, b) in points.items()]
    lines += ['};', '']
    (GAME / 'src' / 'audio' / 'tracks.ts').write_text('\n'.join(lines))


if __name__ == '__main__':
    if sys.argv[1:2] == ['--score']:
        rows = []
        for name in sys.argv[2:]:
            audio = decode(Path(name))
            at, score = best_join(audio)
            rows.append((score, steadiness(audio), at / RATE, name))
        for score, spread, at, name in sorted(rows, reverse=True):
            print(f'{score:.3f} join at {at:5.1f}s, level spread {spread:4.1f} dB  {Path(name).name}')
    else:
        write_tracks({t: build(t, b, l) for t, b, l in TRACKS})
